"""Check that implementation changes keep harness context in sync."""

import subprocess
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]

TRIGGER_PREFIXES = {
    ".agent-harness/",
    ".agents/skills/",
    ".claude/skills/",
    ".opencode/skills/",
    "app/",
    "cmd/",
    "config/",
    "control/",
    "data/",
    "domain/",
    "gradle/",
    "lib/",
    "packages/",
    "protocol/",
    "scripts/",
    "server/",
    "src/",
    "test/",
    "tests/",
    "WORKFLOW.md",
}

TRIGGER_FILES = {
    "build.gradle",
    "build.gradle.kts",
    "CLAUDE.md",
    "Cargo.toml",
    "go.mod",
    "gradle.properties",
    "gradlew",
    "gradlew.bat",
    "Makefile",
    "package.json",
    "pnpm-workspace.yaml",
    "pom.xml",
    "pyproject.toml",
    "settings.gradle",
    "settings.gradle.kts",
    "WORKFLOW.md",
}

SYNC_PREFIXES = {
    ".githooks/",
    ".review/rules/",
    "doc/features/",
    "docs/",
    "harness/docs/",
    "harness/evals/",
    "harness/memory/",
    "harness/trace/",
    "templates/",
}

SYNC_FILES = {
    ".gitignore",
    "AGENTS.md",
    "BLACKBOARD.md",
    "CLAUDE.md",
    "CONSTRAINTS.md",
    "README.md",
    "harness/VERSION",
    "harness.example.yaml",
    "harness.yaml",
    "WORKFLOW.md",
}

IGNORED_SYNC_FILES = {"commit_log.csv"}
IGNORED_SYNC_PREFIXES = {"harness/.local/"}


def run_git(args, check=False):
    result = subprocess.run(
        ["git", *args],
        cwd=ROOT,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    if check and result.returncode != 0:
        raise RuntimeError(result.stderr.strip() or result.stdout.strip())
    return result


def normalize(path_text):
    return path_text.replace("\\", "/").strip()


def changed_files():
    if run_git(["rev-parse", "--is-inside-work-tree"]).returncode != 0:
        print("[WARN] Not inside a git repository; harness sync check skipped.")
        return set()

    files = set()
    commands = [
        ["diff", "--name-only"],
        ["diff", "--cached", "--name-only"],
        ["ls-files", "--others", "--exclude-standard"],
    ]
    upstream = run_git(["rev-parse", "--abbrev-ref", "--symbolic-full-name", "@{u}"])
    if upstream.returncode == 0 and upstream.stdout.strip():
        commands.append(["diff", "--name-only", f"{upstream.stdout.strip()}...HEAD"])

    for command in commands:
        result = run_git(command)
        if result.returncode != 0:
            continue
        files.update(normalize(line) for line in result.stdout.splitlines() if line)
    return files


def is_trigger(path_text):
    path = normalize(path_text)
    if not path or path in IGNORED_SYNC_FILES or any(
        path.startswith(prefix) for prefix in IGNORED_SYNC_PREFIXES
    ):
        return False
    return path in TRIGGER_FILES or Path(path).name in TRIGGER_FILES or any(
        path.startswith(prefix) for prefix in TRIGGER_PREFIXES
    )


def is_sync_artifact(path_text):
    path = normalize(path_text)
    if not path or path in IGNORED_SYNC_FILES or any(
        path.startswith(prefix) for prefix in IGNORED_SYNC_PREFIXES
    ):
        return False
    return path in SYNC_FILES or any(path.startswith(prefix) for prefix in SYNC_PREFIXES)


def main():
    files = changed_files()
    if not files:
        print("[OK] No changed files to check for harness sync.")
        return 0

    triggers = sorted(path for path in files if is_trigger(path))
    sync_artifacts = sorted(path for path in files if is_sync_artifact(path))

    if not triggers:
        print("[OK] No implementation or workflow changes requiring harness sync.")
        return 0
    if sync_artifacts:
        print("[OK] Harness sync artifacts updated for implementation/workflow changes.")
        print("Triggers:")
        for path in triggers:
            print(f"  - {path}")
        print("Sync artifacts:")
        for path in sync_artifacts:
            print(f"  - {path}")
        return 0

    print("[FAIL] Implementation/workflow changes have no harness context update.")
    print("Changed files that require sync:")
    for path in triggers:
        print(f"  - {path}")
    print("Update at least one applicable harness artifact before commit:")
    print("  - AGENTS.md / CONSTRAINTS.md / README.md")
    print("  - WORKFLOW.md")
    print("  - harness.yaml or harness.example.yaml")
    print("  - .review/rules/")
    print("  - doc/features/ or docs/")
    print("  - harness/docs/, harness/memory/, harness/trace/, templates/")
    print("Note: legacy commit_log.csv is not sync evidence and should not be generated by commit-review.")
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
