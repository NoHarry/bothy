#!/usr/bin/env node
// A small client for Bothy's protocol, for a PC next to the device:
//
//   adb forward tcp:8791 localabstract:bothy
//   node bothy.mjs state                 the threads, the current one and how the run stands
//   node bothy.mjs say 去世界之窗         one turn, its items as they come, until it ends
//   node bothy.mjs watch                 every notification until Ctrl-C
//   ... --thread ID                      say or watch in thread ID beside the current one, which stays current
//   node bothy.mjs call thread/list '{}' any request, its answer as JSON
//   node bothy.mjs call                  the requests there are, from the protocol's schema
//
// --port N picks another forwarded port; --approve answers the server's approval requests at the prompt.
// One JSON-RPC message per line, without the "jsonrpc" member, as the server writes them. Every message's types are in
// ../../bothy-protocol/schema/ (JSON Schema and TypeScript), generated by ./gradlew :bothy-protocol:generateSchema.

import fs from "node:fs";
import net from "node:net";
import readline from "node:readline";

/** The protocol's JSON Schema; `methods` lists each method by who sends it. */
export function loadSchema() {
  const file = new URL("../../bothy-protocol/schema/bothy-protocol.schema.json", import.meta.url);
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

export class BothyConnection {
  constructor(socket, { onNotification = () => {}, onRequest = async () => null } = {}) {
    this.socket = socket;
    this.nextId = 1;
    this.pending = new Map();
    this.onNotification = onNotification;
    this.onRequest = onRequest;
    readline.createInterface({ input: socket }).on("line", (line) => this.#receive(line));
    socket.on("close", () => {
      for (const { reject } of this.pending.values()) reject(new Error("connection closed"));
      this.pending.clear();
    });
  }

  request(method, params = {}) {
    const id = this.nextId++;
    this.#send({ id, method, params });
    return new Promise((resolve, reject) => this.pending.set(id, { resolve, reject }));
  }

  notify(method, params = {}) {
    this.#send({ method, params });
  }

  close() {
    this.socket.end();
  }

  #send(message) {
    this.socket.write(`${JSON.stringify(message)}\n`);
  }

  async #receive(line) {
    if (!line.trim()) return;
    const message = JSON.parse(line);
    if (message.method !== undefined && message.id !== undefined) {
      const result = await this.onRequest(message.method, message.params ?? {});
      if (result === null) this.#send({ id: message.id, error: { code: -32001, message: "left unanswered" } });
      else this.#send({ id: message.id, result });
    } else if (message.method !== undefined) {
      this.onNotification(message.method, message.params ?? {});
    } else {
      const waiting = this.pending.get(message.id);
      if (!waiting) return;
      this.pending.delete(message.id);
      if (message.error) waiting.reject(Object.assign(new Error(message.error.message), { code: message.error.code }));
      else waiting.resolve(message.result);
    }
  }
}

/** Connects and shakes hands; resolves to the connection and the server's snapshot. */
export async function connect({ port = 8791, host = "127.0.0.1", approvals = false, ...handlers } = {}) {
  const socket = net.createConnection({ port, host });
  await new Promise((resolve, reject) => socket.once("connect", resolve).once("error", reject));
  const connection = new BothyConnection(socket, handlers);
  const result = await connection.request("initialize", {
    clientInfo: { name: "bothy-cli", version: "1" },
    capabilities: { approvals },
  });
  connection.notify("initialized");
  return { connection, result };
}

/** What `state` prints: a few lines about the snapshot. */
export function describeSnapshot({ serverInfo, protocolVersion, snapshot }) {
  const sections = Object.fromEntries(snapshot.sections.map((section) => [section.type, section]));
  const run = sections.run ?? {};
  const model = sections.model ?? {};
  const active = snapshot.threads.find((thread) => thread.sessionId === snapshot.activeThreadId);
  return [
    `${serverInfo.name} ${serverInfo.version} · protocol ${protocolVersion}`,
    `threads: ${snapshot.threads.length} · current: ${active?.title ?? snapshot.activeThreadId} (${snapshot.thread.items.length} items)`,
    `run: ${run.isRunning ? `running · ${run.activity ?? ""}${run.tool ? ` ${run.tool}` : ""}` : "idle"}${run.runtimeStatus ? ` · ${run.runtimeStatus}` : ""}`,
    `model: ${model.providerLabel ?? ""} ${model.configEditor?.model ?? ""}`.trim(),
  ];
}

/** One line for an item as it starts or changes, or null for those not worth a line. */
export function describeItem(item) {
  switch (item.type) {
    case "userMessage": return `> ${item.fullText}`;
    case "message": return item.role === "ASSISTANT" ? `< ${item.content}` : item.role === "ERROR" ? `! ${item.content}` : null;
    case "toolCall": return `  [${item.status.toLowerCase()}] ${item.toolName}`;
    case "approval": return `  ? approval ${item.pendingId} (${item.status.toLowerCase()})`;
    default: return null;
  }
}

async function ask(question) {
  const prompt = readline.createInterface({ input: process.stdin, output: process.stdout });
  const answer = await new Promise((resolve) => prompt.question(question, resolve));
  prompt.close();
  return answer.trim().toLowerCase();
}

async function main(argv) {
  const port = Number(argv.includes("--port") ? argv[argv.indexOf("--port") + 1] : 8791);
  const approve = argv.includes("--approve");
  const thread = argv.includes("--thread") ? argv[argv.indexOf("--thread") + 1] : null;
  const valued = new Set(["--port", "--thread"]);
  const [command, ...rest] = argv.filter((arg, index) => !arg.startsWith("--") && !valued.has(argv[index - 1]));
  const approvals = async (method, params) => {
    if (method !== "approval/request") return null;
    const yes = await ask(`approve ${params.toolName || params.domain} ${params.argumentsJson ?? ""}? [y/n] `);
    return { decision: yes.startsWith("y") ? "approve" : "deny" };
  };
  let finished;
  const done = new Promise((resolve) => { finished = resolve; });
  const onNotification = (method, params) => {
    if (command === "watch") console.log(method, JSON.stringify(params));
    if (command !== "say" || (thread && params.threadId && params.threadId !== thread)) return;
    if (method === "item/started" || method === "item/updated") {
      const line = describeItem(params.item);
      if (line) console.log(line);
    }
    if (method === "item/delta") process.stdout.write(params.delta);
    if (method === "turn/completed") finished(params.result ? `${params.result.outcome} after ${(params.result.durationMs / 1000).toFixed(1)}s` : "done");
  };
  if (command === "call" && !rest[0]) {
    Object.keys(loadSchema().methods.clientRequests).forEach((method) => console.log(method));
    return;
  }
  const { connection, result } = await connect({ port, approvals: approve, onNotification, onRequest: approvals });
  try {
    if (command === "state") {
      describeSnapshot(result).forEach((line) => console.log(line));
    } else if (command === "say") {
      if (thread) await connection.request("thread/subscribe", { threadId: thread });
      await connection.request("turn/start", thread ? { text: rest.join(" "), threadId: thread, focus: false } : { text: rest.join(" ") });
      console.log(`\n${await done}`);
    } else if (command === "call") {
      console.log(JSON.stringify(await connection.request(rest[0], JSON.parse(rest[1] ?? "{}")), null, 2));
    } else if (command === "watch") {
      if (thread) await connection.request("thread/subscribe", { threadId: thread });
      await new Promise(() => {});
    } else {
      console.log("usage: bothy.mjs [--port N] [--approve] [--thread ID] state | say <text> | watch | call [<method> [json]]");
    }
  } finally {
    connection.close();
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main(process.argv.slice(2)).catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
